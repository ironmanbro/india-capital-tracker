-- Baseline snapshot of production RLS. Reference only; see README.md.
-- Tables WITHOUT any policy on purpose (service role only): app_admins, app_secrets, backfill_weeks, directory_state, shp_filings, site_visits.
-- `events` has a permissive SELECT USING (true) for anon, but anon holds NO table grant on events: the public path is the `stories` view.
-- That is fragile (a single GRANT would expose unreviewed rows). Milestone 1 adds a CI check that anon cannot select from events.

