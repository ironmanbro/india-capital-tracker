#!/usr/bin/env python3
"""Builds site/v2 (the public copy of the new design) from mockups/v2.
  1. build_all.py writes the five data files (nothing is touched if any fetch or check fails);
  2. the public pages and shared assets are copied; owner-only tools (the alias review page and its data) and the profile mock-ups are NOT shipped;
  3. a public config.js is written (lists the pages that exist, so links to unbuilt pages are hidden);
  4. every link and script in the shipped pages is checked against what was written.
Usage: python3 package_site.py [--out site/v2] [--no-data]   (--no-data reuses the data files already in --out)"""
import argparse, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "mockups", "v2")
PAGES = ["monitor.html", "flows.html", "deals.html", "investors.html", "registrations.html", "regulations.html", "limits.html", "watchlist.html", "scorecard.html"]
ASSETS = ["tokens.css", "ui.js", "resolver.js", "watch.js", "push-sw.js"]
DATA = ["data.js", "deals.js", "inv.js", "reg.js", "regs.js", "limits.js", "scorecard.js"]
CONFIG = """/* Public configuration of the /v2 pages. Generated by pipeline/site_v2/package_site.py; edit there, not here.
   aliasSource 'local': names are not grouped for visitors until aliases are confirmed and loaded (see pipeline/aliases/ROLLOUT.md). */
window.ICT_CONFIG = {
  aliasSource: 'local',
  supabaseUrl: 'https://urpphqybqmxlwhjghsmf.supabase.co',
  supabaseKey: 'sb_publishable_zSo8W_FfT_fZEcfMWoumOw_Yv9mmVWB',
  aliasTimeoutMs: 3000,
  pushPublicKey: %s,   /* the VAPID public key switches watchlist alerts on; empty keeps them off (see pipeline/alerts/README.md) */
  shipped: %s,
  homeHref: './',
  classicUrl: '/'
};
"""

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=os.path.join(ROOT, "site", "v2")); ap.add_argument("--no-data", action="store_true")
    a = ap.parse_args(); out = os.path.abspath(a.out)
    if not a.no_data:
        r = subprocess.run([sys.executable, os.path.join(HERE, "build_all.py"), "--out", out]); 
        if r.returncode: sys.exit("data build failed; nothing was packaged")
    os.makedirs(out, exist_ok=True)
    for f in PAGES + ASSETS: shutil.copyfile(os.path.join(SRC, f), os.path.join(out, f))
    shutil.copyfile(os.path.join(SRC, "monitor.html"), os.path.join(out, "index.html"))          # /v2/ opens the Home page
    pk = os.environ.get("ICT_PUSH_PUBLIC_KEY", "").strip()
    if pk and not re.fullmatch(r"[A-Za-z0-9_-]{80,100}", pk): sys.exit("ICT_PUSH_PUBLIC_KEY is not a VAPID public key (URL-safe base64, about 87 characters)")
    open(os.path.join(out, "config.js"), "w").write(CONFIG % (repr(pk), str(PAGES)))
    # keep the folder to exactly what is meant to ship
    keep = set(PAGES + ASSETS + DATA + ["index.html", "config.js"])
    for f in os.listdir(out):
        if f not in keep: os.remove(os.path.join(out, f)); print("removed stray file", f)
    # check every local reference in the shipped pages
    bad = []
    for f in PAGES + ["index.html"]:
        html = open(os.path.join(out, f), encoding="utf-8").read()
        html = re.sub(r"<script>.*?</script>", "", html, flags=re.S)       # links built inside scripts are gated by config.js (shipped list)
        refs = re.findall(r'(?:src|href)="([^"#?]+)', html)
        for r in refs:
            if re.match(r"^(https?:|//|mailto:|/|javascript:)", r) or r in ("./",): continue
            if not os.path.exists(os.path.join(out, r)): bad.append((f, r))
    if bad: sys.exit("broken references: " + str(sorted(set(bad))))
    print("packaged", len(keep), "files into", out, "- all references resolve")

if __name__ == "__main__": main()
