#!/usr/bin/env python3
"""Builds the public home pages (site/, served at /) from mockups/v2.
  1. build_all.py writes the five data files (nothing is touched if any fetch or check fails);
  2. the public pages and shared assets are copied into site/ (the old app lives in site/classic/ and is never touched); owner-only tools (the alias review page and its data) and the profile mock-ups are NOT shipped;
  3. a public config.js is written (lists the pages that exist, so links to unbuilt pages are hidden);
  4. every link and script in the shipped pages is checked against what was written.
Usage: python3 package_site.py [--out site] [--no-data] [--list]  (--list prints the files this script manages, one per line)   (--no-data reuses the data files already in --out)"""
import argparse, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "mockups", "v2")
PAGES = ["monitor.html", "flows.html", "deals.html", "investors.html", "registrations.html", "regulations.html"]
ASSETS = ["tokens.css", "ui.js", "resolver.js"]
DATA = ["data.js", "deals.js", "inv.js", "reg.js", "regs.js"]
CONFIG = """/* Public configuration of the home pages. Generated by pipeline/site_v2/package_site.py; edit there, not here.
   aliasSource 'local': names are not grouped for visitors until aliases are confirmed and loaded (see pipeline/aliases/ROLLOUT.md). */
window.ICT_CONFIG = {
  aliasSource: 'local',
  supabaseUrl: 'https://urpphqybqmxlwhjghsmf.supabase.co',
  supabaseKey: 'sb_publishable_zSo8W_FfT_fZEcfMWoumOw_Yv9mmVWB',
  aliasTimeoutMs: 3000,
  shipped: %s,
  homeHref: '/',
  classicUrl: '/classic/'
};
"""

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=os.path.join(ROOT, "site")); ap.add_argument("--no-data", action="store_true"); ap.add_argument("--list", action="store_true")
    a = ap.parse_args(); out = os.path.abspath(a.out)
    MANAGED = PAGES + ASSETS + DATA + ["index.html", "config.js"]
    if a.list: print("\n".join(sorted(MANAGED))); return
    if not a.no_data:
        r = subprocess.run([sys.executable, os.path.join(HERE, "build_all.py"), "--out", out]); 
        if r.returncode: sys.exit("data build failed; nothing was packaged")
    os.makedirs(out, exist_ok=True)
    for f in PAGES + ASSETS: shutil.copyfile(os.path.join(SRC, f), os.path.join(out, f))
    shutil.copyfile(os.path.join(SRC, "monitor.html"), os.path.join(out, "index.html"))          # / opens the Home page
    for f in PAGES + ["index.html"]:                                                              # promoted: visible to search engines
        q = os.path.join(out, f); t = open(q, encoding="utf-8").read(); open(q, "w", encoding="utf-8").write(t.replace('<meta name="robots" content="noindex">\n', ""))
    open(os.path.join(out, "config.js"), "w").write(CONFIG % str(PAGES))
    # check every local reference in the shipped pages
    bad = []
    for f in PAGES + ["index.html"]:
        html = open(os.path.join(out, f), encoding="utf-8").read()
        html = re.sub(r"<script>.*?</script>", "", html, flags=re.S)       # links built inside scripts are gated by config.js (shipped list)
        refs = re.findall(r'(?:src|href)="([^"#?]+)', html)
        for r in refs:
            if re.match(r"^(https?:|//|mailto:|/|javascript:)", r) or r in ("./",): continue
            if not os.path.exists(os.path.join(out, r)): bad.append((f, r))
    if bad: sys.exit("broken references: " + str(sorted(set(bad))))
    print("packaged", len(MANAGED), "files into", out, "- all references resolve")

if __name__ == "__main__": main()
